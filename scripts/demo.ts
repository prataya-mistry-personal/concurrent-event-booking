/**
 * One-command demo.
 *
 *   npm run demo
 *
 * Runs the same load test twice against the same server -- once through the naive
 * booking path and once through the hardened one -- then demonstrates the expiry
 * reaper. Everything is torn down at the end.
 *
 * A temporary env profile is generated so the demo can use a short hold duration
 * and a fast reaper without touching the developer's .env.
 */

import { spawn } from 'node:child_process';
import { readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import path from 'node:path';

const DEMO_ENV_FILE = '.env.demo';
const HOLD_SECONDS = 8;
const REAPER_MS = 1000;
const PORT = 3210;

const root = process.cwd();

function heading(title: string): void {
  const bar = '='.repeat(72);
  console.log(`\n${bar}\n  ${title}\n${bar}`);
}

/** Builds the demo env profile from the developer's .env, overriding tunables. */
function writeDemoEnv(): void {
  const source = path.join(root, '.env');
  if (!existsSync(source)) {
    throw new Error('.env not found. Copy .env.example to .env first.');
  }

  const overrides: Record<string, string> = {
    HOLD_DURATION_SECONDS: String(HOLD_SECONDS),
    REAPER_INTERVAL_MS: String(REAPER_MS),
    PORT: String(PORT),
  };

  const lines = readFileSync(source, 'utf8').split(/\r?\n/);
  const kept = lines.filter((line) => {
    const key = line.split('=')[0]?.trim();
    return !(key && key in overrides);
  });

  const rendered = [
    '# Generated by scripts/demo.ts. Safe to delete.',
    ...kept,
    ...Object.entries(overrides).map(([k, v]) => `${k}=${v}`),
  ].join('\n');

  writeFileSync(path.join(root, DEMO_ENV_FILE), rendered, 'utf8');
}

function run(command: string, args: string[], label: string): Promise<number> {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, {
      cwd: root,
      // shell:true so `npx`/`ts-node` resolve the same way they do interactively,
      // including on Windows where they are .cmd shims.
      shell: true,
      stdio: 'inherit',
      env: { ...process.env, ENV_FILE: DEMO_ENV_FILE },
    });
    child.on('error', (error) => reject(new Error(`${label} failed to start: ${error.message}`)));
    child.on('close', (code) => resolve(code ?? 1));
  });
}

async function waitForHealth(baseUrl: string, timeoutMs = 20_000): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    try {
      const res = await fetch(`${baseUrl}/health`);
      if (res.ok) return;
    } catch {
      /* not up yet */
    }
    await new Promise((r) => setTimeout(r, 250));
  }
  throw new Error(`Server did not become healthy at ${baseUrl}`);
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function getJson(url: string): Promise<any> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url} -> ${res.status}`);
  return res.json();
}

/** Phase 3: show a hold lapsing and the reaper returning the seat to inventory. */
async function demonstrateExpiry(baseUrl: string): Promise<boolean> {
  const events = await getJson(`${baseUrl}/events`);
  const eventId = events[0].id;

  const seats = await getJson(`${baseUrl}/events/${eventId}/seats`);
  const target = seats.find((s: any) => s.status === 'AVAILABLE');
  if (!target) {
    console.log('  No AVAILABLE seat left to demonstrate expiry.');
    return false;
  }

  const before = events[0].available_seats;
  console.log(`  Seat ${target.id} (${target.label}) starts AVAILABLE. Event availability: ${before}`);

  const held = await fetch(`${baseUrl}/bookings/hold`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ userId: 'demo-abandoner', eventId, seatId: target.id }),
  });
  const heldBody = await held.json();
  if (held.status !== 201) {
    console.log(`  Unexpected hold response ${held.status}`);
    return false;
  }

  const during = await getJson(`${baseUrl}/events`);
  console.log(
    `  Held it and walked away. Availability now ${during[0].available_seats}, ` +
      `hold expires in ${HOLD_SECONDS}s.`
  );

  const waitMs = HOLD_SECONDS * 1000 + REAPER_MS * 3;
  console.log(`  Waiting ${(waitMs / 1000).toFixed(1)}s for the hold to lapse and the reaper to sweep...`);
  await sleep(waitMs);

  const after = await getJson(`${baseUrl}/events`);
  const seatAfter = (await getJson(`${baseUrl}/events/${eventId}/seats`)).find(
    (s: any) => s.id === target.id
  );
  const bookingAfter = await getJson(`${baseUrl}/bookings/${heldBody.booking.id}`);

  console.log(`  Seat ${target.id} is now ${seatAfter.status}, booking is ${bookingAfter.status}.`);
  console.log(`  Event availability recovered to ${after[0].available_seats}.`);

  const ok =
    seatAfter.status === 'AVAILABLE' &&
    bookingAfter.status === 'EXPIRED' &&
    after[0].available_seats === before;

  console.log(`  ${ok ? 'OK — abandoned hold reclaimed automatically.' : 'VIOLATED — seat was not reclaimed.'}`);
  return ok;
}

async function main(): Promise<void> {
  heading('SETUP');
  writeDemoEnv();
  console.log(`  Wrote ${DEMO_ENV_FILE} (hold ${HOLD_SECONDS}s, reaper ${REAPER_MS}ms, port ${PORT})`);

  if ((await run('npm', ['run', 'build'], 'build')) !== 0) {
    throw new Error('Build failed.');
  }
  if ((await run('npx', ['ts-node', 'scripts/reset-db.ts'], 'reset')) !== 0) {
    throw new Error('Reset failed.');
  }
  if ((await run('npx', ['ts-node', 'prisma/seed.ts'], 'seed')) !== 0) {
    throw new Error('Seed failed.');
  }

  const baseUrl = `http://localhost:${PORT}`;
  const server = spawn('node', ['dist/src/server.js'], {
    cwd: root,
    env: { ...process.env, ENV_FILE: DEMO_ENV_FILE },
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  server.stdout.on('data', (chunk) => process.stdout.write(`  [server] ${chunk}`));
  server.stderr.on('data', (chunk) => process.stderr.write(`  [server] ${chunk}`));

  const results: Array<{ label: string; ok: boolean }> = [];

  try {
    await waitForHealth(baseUrl);

    heading('PHASE 1 — NAIVE PATH (read-then-write, no lock, no guarded write)');
    const naive = await run(
      'npx',
      ['ts-node', 'scripts/loadtest.ts', '--url', baseUrl, '--concurrency', '200', '--mode', 'naive'],
      'naive load test'
    );
    results.push({ label: 'naive path oversells as expected', ok: naive === 0 });

    await run('npx', ['ts-node', 'scripts/reset-db.ts'], 'reset');

    heading('PHASE 2 — HARDENED PATH (Redis lock + guarded conditional write)');
    const safe = await run(
      'npx',
      ['ts-node', 'scripts/loadtest.ts', '--url', baseUrl, '--concurrency', '200', '--mode', 'safe'],
      'safe load test'
    );
    results.push({ label: 'hardened path admits exactly one winner', ok: safe === 0 });

    heading('PHASE 3 — ABANDONED HOLD RECLAIM (deadline + reaper)');
    results.push({ label: 'abandoned hold reclaimed', ok: await demonstrateExpiry(baseUrl) });
  } finally {
    server.kill();
    rmSync(path.join(root, DEMO_ENV_FILE), { force: true });
  }

  heading('SUMMARY');
  for (const result of results) {
    console.log(`  ${result.ok ? 'PASS' : 'FAIL'}  ${result.label}`);
  }

  const allOk = results.every((r) => r.ok);
  console.log(`\n  Overall: ${allOk ? 'PASS' : 'FAIL'}\n`);
  process.exit(allOk ? 0 : 1);
}

main().catch((error) => {
  console.error(`\ndemo failed: ${error instanceof Error ? error.message : String(error)}`);
  rmSync(path.join(process.cwd(), DEMO_ENV_FILE), { force: true });
  process.exit(1);
});
